function L01AEsxtrapag26(){
    alert("02) Operações Combinadas com Quatro Variáveis Inteiras")
    let valorA = parseInt(prompt("Escreva o valor A:"))
    let valorB = parseInt(prompt("Escreva o valor B: "))
    let valorC = parseInt(prompt("Escreva o valor C: "))
    let valorD = parseInt(prompt("Escreva o valor D:"))

    alert(`Valor produto P: ${valorA * valorC}`)
    alert(`Valor produto Q: ${valorB + valorD}`)
}